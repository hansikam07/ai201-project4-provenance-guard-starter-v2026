"""
Turning two numbers into one, and one number into something a person can read.
← YOU BUILD THIS IN MILESTONES 4 AND 5

Two functions live here, and both are stubs.

`combine_signals` is where your false-positive decision from Milestone 1
actually gets made. Everything above it — the labels, the appeal path — is
downstream of a number this function produced.

`score_to_label` is where you stop writing for a machine and start writing for
a person. A score of 0.62 means nothing to a writer.

⚠️ Your README's **Signals and Scoring** section has to name the file and
function holding your combining rule. The grader checks your code against what
you claim, so that line should read `scoring.py::combine_signals`.
"""

import config

LABEL_HUMAN = "We think this was probably written by a person."
LABEL_UNSURE = (
    "We can't tell for sure whether a person or AI wrote this. Nothing is being "
    "held against you, and you can ask for a review if you'd like."
)
LABEL_AI = (
    "This looks like it may have been generated by AI. These checks can be wrong. "
    "If you wrote it yourself, you can appeal and it will be marked for review."
)


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine two 0-1 signals into one 0-1 score. Higher means more likely AI.

    The rule, in words: take the weighted average of the two scores, using
    config.WEIGHT_MODEL_SIGNAL and config.WEIGHT_STYLE_SIGNAL (0.5 each, so a
    plain average). Then check whether the two signals disagree, meaning they
    are further apart than config.DISAGREEMENT_GAP (0.4). If they do, two
    methods splitting is itself a sign we don't know, so the average is pulled
    toward 0.5 ("unsure") by config.DISAGREEMENT_PULL (0.5), which halves its
    distance from 0.5:

        result = 0.5 + (average - 0.5) * (1 - pull)

    If they agree, the plain average is returned unchanged. The pull is
    deliberately symmetric: it softens a likely-AI reading and a likely-human
    reading equally.
    """
    total = config.WEIGHT_MODEL_SIGNAL + config.WEIGHT_STYLE_SIGNAL
    avg = (
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score
    ) / total

    if abs(model_score - style_score) > config.DISAGREEMENT_GAP:
        avg = 0.5 + (avg - 0.5) * (1 - config.DISAGREEMENT_PULL)

    return round(min(max(avg, 0.0), 1.0), 4)


def score_to_label(score: float) -> tuple[str, str]:
    """
    Turn a score into a guess and the text a reader actually sees.
    Scores at or below HUMAN_THRESHOLD are "human", at or above AI_THRESHOLD
    are "ai", and everything between is "unsure", so each score gets one label.

    Returns:
        (guess, label_text) — where `guess` is a short machine-readable string
        like "ai" / "human" / "unsure", and `label_text` is the full sentence
        shown to a person.

    ⚠️ Write the label text for someone who has never heard the word
    "threshold".

        ✗ "human, 0.81 confidence"
        ✓ "We think this was probably written by a person."

    All three labels have to be **reachable**. If no score can produce one of
    them, your ranges have a gap — and Milestone 5 asks you to submit text that
    produces each one, which is how you'd find out.

    The hardest one to write is "unsure". It has to admit uncertainty without
    sounding like an accusation, because the person reading it may well have
    written every word themselves. Your breakout asks your group what they'd
    think if they got it on their own work. That question is the whole
    milestone.
    """
    if score >= config.AI_THRESHOLD:
        return "ai", LABEL_AI
    if score <= config.HUMAN_THRESHOLD:
        return "human", LABEL_HUMAN
    return "unsure", LABEL_UNSURE


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 – {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} – 1.00"),
    ]
